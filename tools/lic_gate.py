"""Verificarea licentei in interiorul fiecarui modul compilat (.fas).

    from lic_gate import inject
    text = inject(text, "TopoKitAnexe.lsp")      # inainte de compilare, doar cu licentiere

Incarcatorul TopoKitLoad.lsp ramane .lsp necompilat, deci verificarea din el se poate
ocoli (editand incarcatorul sau cu (load "TopoKit.fas") direct). De aceea fiecare modul
primeste propria verificare:

  - la inceputul fisierului: functii cu prefix propriu modulului (TKG-<MODUL>:) care
    gasesc TopoKit.exe ca incarcatorul (Contents\\install.txt, apoi registrul
    HKCU\\Software\\TopoKit\\InstallDir), ruleaza ascuns "TopoKit.exe" /license si asteapta;
    doar codul de iesire 0 inseamna licenta buna. Orice eroare (lipsa WScript.Shell,
    lipsa TopoKit.exe, alt cod) inseamna "fara licenta" (fail closed);
  - la sfarsitul fisierului: daca licenta lipseste, toate comenzile c: definite in modul
    sunt redefinite ca stub-uri care afiseaza un mesaj si deschid TopoKit.exe.

Functiile ajutatoare ale modulului (fara c:) raman definite. Pe succes nu se afiseaza
nimic. Codul adaugat e ASCII si foloseste doar functii comune LISPSYS 0 si 1.
inject() e determinista si idempotenta (marcajul MARK).
"""
import pathlib
import re

MARK = ";;; @@TKGATE@@"
END_MARK = ";;; @@TKGATE-END@@"
MSG_RO = "TopoKit: licenta lipsa sau expirata - deschideti TopoKit pentru activare."
MSG_EN = "TopoKit: licence missing or expired - open TopoKit to activate it."
CMD_RE = re.compile(r"\(\s*defun\s+c:([^\s()'\";]+)", re.I)


def module_id(module_name):
    """Prefixul functiilor injectate: TKG-<NUMELE MODULULUI, doar litere si cifre>."""
    stem = pathlib.PurePath(str(module_name).replace("\\", "/")).stem
    ident = re.sub(r"[^A-Z0-9]", "", stem.upper()) or "MODULE"
    return "TKG-" + ident


def commands(text):
    """Comenzile (defun c:NUME ...) din sursa, cu litere mari, sortate, fara dubluri."""
    return sorted({m.upper() for m in CMD_RE.findall(text)})


def _english(module_name):
    parts = pathlib.PurePath(str(module_name).replace("\\", "/")).parts[:-1]
    return any(p.lower() == "en" for p in parts)


def _lisp_str(s):
    assert s.isascii() and '"' not in s and "\\" not in s, s
    return '"' + s + '"'


def header(module_name):
    p = module_id(module_name)
    return f"""{MARK} licence gate - generated by tools/lic_gate.py, do not edit
(setq *{p}:OK* nil)
(defun {p}:Slash (s) (vl-string-right-trim "\\\\/" (vl-string-translate "/" "\\\\" s)))
(defun {p}:Dir (f) (if (= (type f) 'STR) (vl-filename-directory f)))
;; TopoKit.exe: Contents\\install.txt (prima linie = folderul instalarii), apoi registrul
(defun {p}:Exe (/ k l f fh)
  (setq k "HKEY_CURRENT_USER\\\\Software\\\\TopoKit")
  (foreach d (list (vl-registry-read k "ContentsDir")
                   ({p}:Dir (findfile "TopoKitLoad.fas")) ({p}:Dir (findfile "TopoKitLoad.lsp"))
                   ({p}:Dir (findfile "TopoKit.fas")) ({p}:Dir (findfile "TopoKit.lsp"))
                   ({p}:Dir ({p}:Dir (findfile "TopoKit.fas"))) ({p}:Dir ({p}:Dir (findfile "TopoKit.lsp"))))
    (if (and (= (type d) 'STR) (/= d "")
             (setq f (findfile (strcat ({p}:Slash d) "\\\\install.txt")))
             (setq fh (open f "r")))
      (progn (setq l (cons (read-line fh) l)) (close fh))))
  (vl-some '(lambda (d)
              (if (and (= (type d) 'STR) (/= (setq d (vl-string-trim " \\t\\r\\n" d)) "")
                       (findfile (strcat ({p}:Slash d) "\\\\TopoKit.exe")))
                (strcat ({p}:Slash d) "\\\\TopoKit.exe")))
           (append (reverse l) (list (vl-registry-read k "InstallDir")))))
;; T doar daca "TopoKit.exe" /license iese cu 0
(defun {p}:Check (/ exe sh r)
  (vl-load-com)
  (if (setq exe ({p}:Exe))
    (progn
      (setq sh (vl-catch-all-apply 'vlax-create-object (list "WScript.Shell")))
      (if (and sh (not (vl-catch-all-error-p sh)))
        (progn
          (setq r (vl-catch-all-apply 'vlax-invoke (list sh 'Run (strcat "\\"" exe "\\" /license") 0 :vlax-true)))
          (vl-catch-all-apply 'vlax-release-object (list sh))))))
  (if (and (numberp r) (= r 0)) T))
(defun {p}:Stub (/ exe)
  (princ "\\n{MSG_EN if _english(module_name) else MSG_RO}")
  (setq exe (vl-catch-all-apply '{p}:Exe nil))
  (if (= (type exe) 'STR) (vl-catch-all-apply 'startapp (list exe)))
  (princ))
(setq *{p}:OK* (eq (vl-catch-all-apply '{p}:Check nil) T))
;;; end of licence gate header

"""


def footer(module_name, cmds):
    p = module_id(module_name)
    names = " ".join(_lisp_str(c) for c in cmds)
    return f"""
{END_MARK} licence gate: without a licence every command of this module becomes a stub
(if (not *{p}:OK*)
  (foreach c '({names})
    (eval (list 'defun (read (strcat "C:" c)) '() (list '{p}:Stub)))))
(princ)
"""


def inject(text: str, module_name: str) -> str:
    """Sursa modulului cu verificarea licentei adaugata la inceput si stub-urile la sfarsit."""
    if MARK in text:
        return text
    body = text if text.endswith("\n") else text + "\n"
    return header(module_name) + body + footer(module_name, commands(text))


if __name__ == "__main__":
    import sys
    for f in sys.argv[1:]:
        print(inject(pathlib.Path(f).read_text(encoding="utf-8"), f), end="")
